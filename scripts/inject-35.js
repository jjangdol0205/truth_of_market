for (const id in analyses) {
  if (archive[id]) {
    archive[id].aiAnalysis = analyses[id];
  }
}

// 기존 큐레이션 해제
for (const id in archive) archive[id].isCurated = false;

const todayArticles = Object.values(archive)
  .filter(a => a.date >= '2026-07-01') // 7/1 00시 이후 (7/2 실행 시 오늘 뉴스 범위)
  .sort((a, b) => {
    const aHasAI = a.aiAnalysis ? 1 : 0;
    const bHasAI = b.aiAnalysis ? 1 : 0;
    if (bHasAI !== aHasAI) return bHasAI - aHasAI;
    return new Date(b.date) - new Date(a.date);
  });

const byIndustry = {};
todayArticles.forEach(a => {
  const ind = a.followingIndustry || 'General';
  if (!byIndustry[ind]) byIndustry[ind] = [];
  if (byIndustry[ind].length < 5) byIndustry[ind].push(a);
});

const candidates = [];
for (const ind in byIndustry) {
  candidates.push(...byIndustry[ind]);
}

candidates.forEach(a => {
  archive[a.id].isCurated = true;
});

fs.writeFileSync('news-archive.json', JSON.stringify(archive, null, 2));

console.log('성공적으로 AI 주입 및 큐레이션 완료! 개수:', candidates.length);

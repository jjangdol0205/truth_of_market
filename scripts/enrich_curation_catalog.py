def enrich_product_list(plist):
    for prod in plist:
        pid = prod["id"]
        # Update image paths
        prod["image"] = f"src/images/products/{pid}.webp"
        prod["imageFallback"] = f"src/images/products/{pid}.svg"
        prod["thumbnail"] = f"src/images/products/{pid}.webp"

        # Fix URL issues if any
        if pid == "prod_ch_dev_1":
            # Fix malformed URI encoding %Bi -> %B9%84 (비)
            if "%Bi" in prod.get("url", ""):
                prod["url"] = prod["url"].replace("%Bi", "%B9%84")
            if "%Bi" in prod.get("affiliateUrl", ""):
                prod["affiliateUrl"] = prod["affiliateUrl"].replace("%Bi", "%B9%84")
        if pid == "prod_inf_gear_1":
            # Fix url vs affiliateUrl mismatch
            prod["affiliateUrl"] = prod["url"]

        # Enrich 5-component metadata
        if pid in metadata_dict:
            meta = metadata_dict[pid]
            prod["specs"] = meta["specs"]
            prod["whyWePicked"] = meta["whyWePicked"]
            prod["buyingGuide"] = meta["buyingGuide"]
            prod["momReviews"] = meta["momReviews"]

